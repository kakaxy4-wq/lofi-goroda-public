"""Пакет для МТС Маркетолога (реклама в Telegram): тексты, баннеры, видео, сводка → promo/mts/lofi-goroda-mts.zip.
Требования площадки: заголовок ≤ 40, текст ≤ 160 символов; баннер PNG/JPEG ≤ 5 МБ; видео MP4 ≤ 20 МБ, 3–60 с.
Кадры сцен берёт из записи tools/make_promo.py (FRAMES), ролики — из promo/."""
import csv
import shutil
import sys
import zipfile
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
FRAMES = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "promo" / "frames"
OUT = ROOT / "promo" / "mts"
SITE = "https://lofi-goroda.ru"

ADS = [  # id, заголовок, текст, город-страница ('' — главная), баннер (кадр сцены), видео
    ("v1", "Лофи-радио с видом на город",
     "Уютная комната, лампа, кот и живое окно в 15 городов России. Настоящие время и погода. Бесплатно, без регистрации.",
     "", "kazan", "lofi-goroda-promo.mp4"),
    ("v2", "Северное сияние под лофи",
     "Мурманск, Казань, Владивосток: пиксельное окно в город и спокойная музыка для работы и учёбы. Бесплатно, в браузере.",
     "murmansk", "murmansk", "lofi-murmansk.mp4"),
    ("v3", "Фон для работы: лофи и город за окном",
     "Работайте под белую ночь Санкт-Петербурга или закат в Сочи. Таймер, звуки города, без рекламы и регистрации.",
     "piter", "piter", "lofi-piter.mp4"),
    ("v4", "Найдите тигра на сопке",
     "В каждом из 15 городов спрятаны секреты: тигр во Владивостоке, сияние в Мурманске. Лофи-радио, бесплатно.",
     "vladivostok", "vladivostok", "lofi-vladivostok.mp4"),
    ("v5", "Лофи-радио вашего города",
     "Выберите город от Калининграда до Иркутска и слушайте лофи под его настоящую погоду и время. Бесплатно.",
     "", "vologda", "lofi-vologda.mp4"),
]


SQUARE_CENTER = {'kazan': 225, 'vologda': 330, 'piter': 260, 'murmansk': 230, 'vladivostok': 255}


def link(ad_id, page):
    return f"{SITE}/{page + '/' if page else ''}?from=mts_{ad_id}"


errors = [f"{a[0]}: заголовок {len(a[1])} > 40" for a in ADS if len(a[1]) > 40]
errors += [f"{a[0]}: текст {len(a[2])} > 160" for a in ADS if len(a[2]) > 160]
if errors:
    sys.exit("Длины не проходят: " + "; ".join(errors))

if OUT.exists():
    shutil.rmtree(OUT)
(OUT / "banners").mkdir(parents=True)
(OUT / "video").mkdir()

for ad_id, _, _, _, scene, video in ADS:
    im = Image.open(FRAMES / f"clip_{scene}_0120.png").convert("RGB")       # 480×270, пиксели без размытия
    im.resize((1920, 1080), Image.NEAREST).save(OUT / "banners" / f"{ad_id}-{scene}-16x9.png", optimize=True)
    cx = SQUARE_CENTER.get(scene, 240)                                        # главное в кадре — в центре квадрата
    sq = im.crop((cx - 135, 0, cx + 135, 270)).resize((1080, 1080), Image.NEAREST)
    sq.save(OUT / "banners" / f"{ad_id}-{scene}-1x1.png", optimize=True)
    shutil.copy2(ROOT / "promo" / video, OUT / "video" / f"{ad_id}-{video}")

with open(OUT / "объявления.csv", "w", newline="", encoding="utf-8-sig") as f:
    w = csv.writer(f, delimiter=";")
    w.writerow(["id", "заголовок", "символов", "текст", "символов", "ссылка", "баннер 16:9", "баннер 1:1", "видео"])
    for ad_id, h, t, page, scene, video in ADS:
        w.writerow([ad_id, h, len(h), t, len(t), link(ad_id, page),
                    f"banners/{ad_id}-{scene}-16x9.png", f"banners/{ad_id}-{scene}-1x1.png", f"video/{ad_id}-{video}"])

rows = "\n".join(f"| {a[0]} | {a[1]} ({len(a[1])}) | {a[2]} ({len(a[2])}) | {link(a[0], a[3])} |" for a in ADS)
(OUT / "СВОДКА.md").write_text(f"""# Лофи-города — сводка для рекламы в Telegram (МТС Маркетолог)

**Продукт:** {SITE} — бесплатное лофи-радио в браузере с живым пиксельным окном в 15 городов России
(Санкт-Петербург, Казань, Владивосток, Мурманск, Калининград, Нижний Новгород, Екатеринбург, Сочи, Иркутск,
Самара, Великий Новгород, Владимир, Вологда, Ярославль, Краснодар). Настоящие время и погода города, звуки
улицы, секреты в каждом городе. Без регистрации, без рекламы, без оплаты. Возраст: 0+.

**Цель кампании:** переходы на сайт и прослушивание эфира (нажатие ▶). Оценка — по нашей статистике
сайта по меткам `?from=mts_v1…v5` (команда `python tools/stats.py 7`).

**Аудитория и таргетинг (предложение):**
- гео — Россия; язык — русский;
- темы каналов: музыка (лофи, чилаут, джаз), учёба и продуктивность, работа из дома и IT,
  путешествия по России, города (Санкт-Петербург, Казань, Владивосток, Мурманск…), уютный контент и арт;
- для городских объявлений (v2 Мурманск, v3 Санкт-Петербург, v4 Владивосток) — каналы этих городов;
- время показа — вечер и выходные (фон для отдыха), будни днём (фон для работы и учёбы).

**Объявления** (в скобках — число символов; лимиты 40 / 160):

| id | заголовок | текст | ссылка |
|---|---|---|---|
{rows}

**Материалы в архиве:**
- `объявления.csv` — то же в таблице (UTF-8, разделитель «;») для копирования в кабинет;
- `banners/` — баннеры PNG 1920×1080 (16:9) и 1080×1080 (1:1), каждый меньше 5 МБ;
- `video/` — видео MP4 1920×1080 с лофи-треком: общий ролик 51 с и городские по 8 с (до 20 МБ, 3–60 с).

Все картинки и видео — настоящие кадры сайта (отрисованы движком сайта), без постобработки.

**Маркировка рекламы (38-ФЗ):** размещение через МТС Маркетолог — платная реклама. erid присваивает
и данные в ОРД передаёт сама площадка; в кабинете нужно указать данные рекламодателя (ФИО, ИНН физлица
или самозанятого). Проверьте, что объявление получило erid до запуска.

**Права:** сцены нарисованы кодом проекта; музыка в роликах — сгенерирована ACE-Step 1.5 (MIT) по заказу автора;
шрифт подписей Pangolin — SIL OFL 1.1. Упомянутые города и объекты — номинативно, без чужих логотипов.
""", encoding="utf-8")

zp = OUT / "lofi-goroda-mts.zip"
with zipfile.ZipFile(zp, "w", zipfile.ZIP_DEFLATED) as z:
    for p in sorted(OUT.rglob("*")):
        if p.is_file() and p != zp:
            z.write(p, p.relative_to(OUT))
print(zp, round(zp.stat().st_size / 1e6, 1), "MB")
for p in sorted(OUT.rglob("*")):
    if p.is_file() and p.suffix in (".png", ".mp4"):
        print(f"  {p.relative_to(OUT)}  {p.stat().st_size / 1e6:.1f} MB")
