"""Заполняет шаблон массового создания кампаний МТС Маркетолога (лист «Реклама в каналах»).
Запуск: python tools/fill_mts_template.py "<путь к campaigns-template.xlsx>" → promo/mts/lofi-goroda-campaigns.xlsx
Медиа должны лежать по публичным ссылкам: tools/make_mts_pack.py копирует их в site/promo/ (выкладывается деплоем).
Бюджеты и даты — стартовые значения для теста, владелец меняет их в файле перед загрузкой."""
import shutil
import sys
from pathlib import Path

import openpyxl

ROOT = Path(__file__).resolve().parents[1]
SRC = Path(sys.argv[1])
OUT = ROOT / "promo" / "mts" / "lofi-goroda-campaigns.xlsx"
MEDIA = "https://lofi-goroda.ru/promo/"
EXCLUDE = "Политика ,Ставки и азартные игры,Криптовалюты,Религия и духовность"  # «Политика » — с пробелом, как в справочнике

# id, название кампании, текст (≤160), страница, темы показа, медиа (тип, файл)
CAMPAIGNS = [
    ("v1", "Лофи-города v1 — общий ролик, музыка и досуг",
     "Лофи-радио с видом на город: уютная комната, кот и живое окно в 15 городов России. Настоящие время и погода. Бесплатно.",
     "", "Музыка,Отдых и развлечения,Искусство и дизайн,Хобби", ("Видео", "v1-lofi-goroda-promo.mp4")),
    ("v2", "Лофи-города v2 — Мурманск, северное сияние, путешествия",
     "Северное сияние под лофи: пиксельное окно в Мурманск и ещё 14 городов, спокойная музыка для работы и отдыха. Бесплатно.",
     "murmansk", "Путешествия и туризм,Интересные факты,Отдых и развлечения", ("Видео", "v2-lofi-murmansk.mp4")),
    ("v3", "Лофи-города v3 — фон для учёбы и работы",
     "Фон для работы и учёбы: лофи под белую ночь Санкт-Петербурга или закат в Сочи. Таймер, звуки города, без регистрации.",
     "piter", "Образование,Мотивация и саморазвитие,Интернет и технологии,Изучение иностранных языков", ("Видео", "v3-lofi-piter.mp4")),
    ("v4", "Лофи-города v4 — секреты, тигр во Владивостоке",
     "Найдите тигра на сопке! В каждом из 15 городов спрятаны секреты: сияние в Мурманске, Онфим в Новгороде. Лофи-радио, бесплатно.",
     "vladivostok", "Видеоигры,Интересные факты,Хобби,Юмор и мемы", ("Видео", "v4-lofi-vladivostok.mp4")),
    ("v5", "Лофи-города v5 — города России, история и культура",
     "Лофи-радио вашего города: от Калининграда до Иркутска, с настоящей погодой и временем за окном. Бесплатно, в браузере.",
     "", "Путешествия и туризм,История,Культура и мероприятия,Книги", ("Изображение", "v5-vologda-16x9.png")),
]
# Бюджет владельца: 1500 ₽ в неделю. При бюджете кампании < 5000 ₽ CPM фиксирован 400 ₽ → ~3750 показов на всё;
# поэтому 3 кампании по 500 ₽ (≈1250 показов каждая), а не 5 по 300 — иначе сравнивать нечего.
ACTIVE = ("v1", "v2", "v3")
BUDGET, CPM, START, END = 500, 400, "2026-10-08", "2026-10-14"

for c in CAMPAIGNS:
    assert len(c[2]) <= 160, (c[0], len(c[2]))
    assert len(c[1]) <= 100, (c[0], len(c[1]))

OUT.parent.mkdir(parents=True, exist_ok=True)
shutil.copy2(SRC, OUT)
wb = openpyxl.load_workbook(OUT)
ws = wb["Реклама в каналах"]
col = {}
for cell in ws[1]:  # колонки ищем по заголовку, а не по букве: шаблон обновляется
    if cell.value:
        col[" ".join(str(cell.value).replace("\xa0", " ").split())] = cell.column_letter


def put(row, header_start, value):
    key = next(k for k in col if k.startswith(header_start))
    ws[f"{col[key]}{row}"] = value


for i, (cid, name, text, page, topics, (mtype, mfile)) in enumerate(c for c in CAMPAIGNS if c[0] in ACTIVE):
    r = 3 + i
    put(r, "Название кампании", name)
    put(r, "Настройка аудитории", "По темам")
    put(r, "[По темам] Темы каналов, в которых показывать", topics)
    put(r, "[По темам] Темы каналов, которые нужно исключить", EXCLUDE)
    put(r, "Текст объявления", text)
    put(r, "Ссылка в кнопке", f"https://lofi-goroda.ru/{page + '/' if page else ''}?from=mts_{cid}")
    put(r, "Текст на кнопке", "Открыть")
    put(r, "Название компании", "Лофи-города")
    put(r, "Медиа", mtype)
    put(r, "Ссылка на медиа", MEDIA + mfile)
    put(r, "Юридическая информация", "[0+]")
    put(r, "Комментарий для модератора",
        "Бесплатный некоммерческий сайт-радио, без продаж и регистрации. Медиа — настоящие кадры сайта.")
    put(r, "Категория товара или услуги", "Интернет-сервисы")
    put(r, "Ваш бюджет на рекламу", BUDGET)
    put(r, "CPM без НДС", CPM)
    put(r, "Ограничение показов в сутки", "3 показа на человека")
    put(r, "Дата старта кампании", START)
    put(r, "Дата завершения кампании", END)
    put(r, "Равномерность", "Распределить показы по дням")

wb.save(OUT)
print(OUT)
