function env(ms, local) {
  const mo = local.getUTCMonth() + 1, day = local.getUTCDate();
  const train = trainAt(ms);
  return {
    train,
    covered: train.dark > 0.5, // в тоннеле дождя за окном нет
    winter: mo >= 11 || mo <= 3 || (mo === 10 && day >= 20) || (mo === 4 && day < 25),
    autumn: (mo === 9 && day >= 5) || (mo === 10 && day < 20),
  };
}

const locate = (ms) => placeAt(trainAt(ms).km);

// Подзаголовок под названием: откуда и куда едем прямо сейчас
function subtitleAt(ms) {
  const tr = trainAt(ms), km = Math.round(tr.km);
  if (tr.at) return `Стоянка: ${tr.at.name} · дальше ${tr.next.name}`;
  if (tr.tunnel) return `${tr.tunnel.name} · к станции ${tr.next.name}`;
  return `${tr.prev.name} → ${tr.next.name} · ${km} км`;
}
// Подсказка при наведении на вокзал — с названием станции (на перегоне вокзала нет, см. hotspotOn)
function labelAt(id, env) {
  const tr = env?.train;
  return id === 'station' && tr?.at ? `Станция ${tr.at.name}` : null;
}
// Ближайшие события для строки «Что сейчас»: стоянки по расписанию
function moments(e) {
  return upcoming(e.ms, 2).map((s) => ({ title: `стоянка: ${s.st.name}`, atMs: s.at }));
}

