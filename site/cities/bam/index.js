function ticker(e) {
  const tr = e.train, lines = []; // «где мы» — в подзаголовке и на схеме маршрута, не в строке
  for (const [a, b, line] of ALONG) if (tr.km >= a && tr.km <= b) lines.push(line);
  if (tr.speed > 0 && !tr.tunnel) lines.push(tr.km < ELECTRIC_TO ? 'До Таксимо БАМ электрифицирован: за окном мелькают опоры контактной сети.' : 'После Таксимо состав ведёт тепловоз — вдоль пути только столбы связи.');
  if (e.autumn) lines.push('Осень: лиственницы вдоль БАМа желтеют — тайга становится золотой.');
  if (e.winter) lines.push('Зимой лиственница сбрасывает хвою: тайга стоит прозрачная, в инее.');
  lines.push('Чай в купе — в стакане с подстаканником.');
  return lines;
}

