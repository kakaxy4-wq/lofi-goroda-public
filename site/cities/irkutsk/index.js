function env(ms, local) {
  const mo = local.getUTCMonth() + 1, day = local.getUTCDate();
  return {
    winter: mo === 12 || mo <= 3 || (mo === 11 && day >= 10),
    frozen: false, // ниже Иркутской ГЭС Ангара не замерзает круглый год
    autumn: (mo === 9 && day >= 5) || mo === 10 || (mo === 11 && day < 10),
    navigation: mo >= 6 && mo <= 9,
  };
}

function ticker(e) {
  const lines = [], h = e.local.getUTCHours(), mo = e.local.getUTCMonth() + 1;
  if (isCityDay(e.local) && h >= 10 && h < 23) lines.push('День города: Иркутск основан в 1661 году, праздник — в первые выходные июня.');
  if (e.winter && e.weather.temp <= -15) lines.push('Мороз: Ангара парит — над тёплой водой стоит туман, на деревьях иней.');
  else if (e.winter) lines.push('Ангара в Иркутске не замерзает: ниже ГЭС течёт быстрая глубинная вода.');
  if (e.sun.alt < -2) lines.push('Московские ворота и храмы Нижней набережной в подсветке.');
  if (h >= 6 && h < 23) lines.push('По Глазковскому мосту идут трамваи — к вокзалу и обратно.');
  if (e.autumn) lines.push('Сибирская осень: берёзы и тополя на набережных желтеют.');
  if (mo >= 6 && mo <= 8 && h >= 18 && h <= 22) lines.push('Летний вечер на Ангаре: вода холодная даже в жару — она пришла из Байкала.');
  const st = stalls(e);
  if (st.includes('buuzy')) lines.push('На набережной лепят буузы — бурятские позы на пару.');
  if (st.includes('nuts')) lines.push('Сезон кедрового ореха: продают шишки и калёные орешки.');
  if (st.includes('tea')) lines.push('Холодно: в ларьке наливают горячий чай с молоком.');
  return lines;
}

