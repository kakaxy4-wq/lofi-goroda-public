function env(ms, local) {
  const mo = local.getUTCMonth() + 1, day = local.getUTCDate();
  return {
    winter: mo === 12 || mo <= 2 || (mo === 3 && day <= 20) || (mo === 11 && day >= 20),
    frozen: (mo === 12 && day >= 5) || mo === 1 || mo === 2 || mo === 3 || (mo === 4 && day <= 2), // ледостав с конца ноября — декабря до начала апреля
    autumn: (mo === 9 && day >= 10) || mo === 10 || (mo === 11 && day < 20),
    navigation: (mo >= 5 && mo <= 9) || (mo === 10 && day <= 5),
  };
}

function ticker(e) {
  const lines = [], h = e.local.getUTCHours(), mo = e.local.getUTCMonth() + 1, d = e.local.getUTCDate();
  if (mo === 7 && d === 26) lines.push('26 июля — День берестяной грамоты: в этот день в 1951 году в Новгороде нашли первую грамоту.');
  if (e.frozen) lines.push('Волхов подо льдом. По выходным на льду сидят рыбаки.');
  else if (e.navigation && h >= 10 && h <= 21) lines.push('Навигация: от причала «Ярославово Дворище» теплоходы ходят по Волхову и на Ильмень.');
  if (e.sun.alt < 0 && e.sun.alt > -12) lines.push('Стены Детинца и Софийский собор в вечерней подсветке.');
  if (mo === 6 && h >= 20 && h <= 23) lines.push('Июнь: солнце садится прямо за Детинцем, на северо-западе.');
  if (e.autumn) lines.push('Осень: Кремлёвский парк желтеет за стенами Детинца.');
  if (mo >= 6 && mo <= 8 && h >= 11 && h <= 19 && e.weather.kind === 'clear') lines.push('На Кремлёвском пляже под стенами загорают и купаются.');
  const st = stalls(e);
  if (st.includes('icecream')) lines.push('На набережной: мороженое, горячие пирожки и берестяные сувениры.');
  else if (st.includes('sbiten')) lines.push('На набережной наливают горячий сбитень и чай, к ним — пирожки.');
  return lines;
}

