function env(ms, local) {
  const mo = local.getUTCMonth() + 1, day = local.getUTCDate();
  return {
    winter: mo === 12 || mo <= 3 || (mo === 11 && day >= 20),
    frozen: (mo === 12 && day >= 10) || mo === 1 || mo === 2 || mo === 3 || (mo === 4 && day <= 8), // ледостав в декабре, ледоход в начале апреля
    autumn: (mo === 9 && day >= 10) || mo === 10 || (mo === 11 && day < 20),
    navigation: (mo >= 5 && mo <= 9) || (mo === 10 && day <= 10),
  };
}

function ticker(e) {
  const lines = [], h = e.local.getUTCHours(), mo = e.local.getUTCMonth() + 1;
  if (cableOn(e)) lines.push('Канатная дорога работает: кабины идут над Волгой между Нижним и Бором, 12,5 минуты в пути.');
  else { const [a] = cableHours(e.local); lines.push(`Канатная дорога закрыта — первые кабины пойдут в ${Math.floor(a / 60)}:${String(a % 60).padStart(2, '0')}.`); }
  if (e.frozen) lines.push('Волга подо льдом. По выходным на льду сидят рыбаки.');
  else if (e.navigation && h >= 8 && h <= 21) lines.push('Навигация: по Волге идут теплоходы, от Речного вокзала уходят «Метеоры» и «Валдаи».');
  if (e.sun.alt < 0 && e.sun.alt > -12) lines.push('Кремль и Александро-Невский собор в вечерней подсветке.');
  if (e.autumn) lines.push('Осень: откосы под Кремлём желтеют над Волгой.');
  if (mo >= 6 && mo <= 8 && h >= 18 && h <= 22) lines.push('Летний вечер: над Волгой носятся стрижи.');
  const st = stalls(e);
  if (st.includes('icecream')) lines.push('На набережной: мороженое, кукуруза и хохлома в сувенирном ларьке.');
  else if (st.includes('tea')) lines.push('На набережной наливают горячий чай, к нему — городецкий пряник.');
  return lines;
}

