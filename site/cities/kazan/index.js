function env(ms, local) {
  const mo = local.getUTCMonth() + 1, day = local.getUTCDate();
  return {
    winter: mo === 12 || mo <= 3 || (mo === 11 && day >= 20),
    frozen: mo === 12 || mo === 1 || mo === 2 || mo === 3 || (mo === 4 && day <= 5), // Казанка подо льдом
    autumn: (mo === 9 && day >= 10) || mo === 10 || (mo === 11 && day < 20),
    navigation: (mo >= 5 && mo <= 9) || (mo === 10 && day <= 15),
  };
}

function ticker(e) {
  const lines = [], h = e.local.getUTCHours(), mo = e.local.getUTCMonth() + 1;
  if (e.frozen) lines.push('Казанка подо льдом — по берегам лыжня и рыбаки.');
  else if (e.navigation && h >= 9 && h <= 22) lines.push('Навигация: по Казанке ходят прогулочные теплоходы.');
  if (mo >= 6 && mo <= 8 && h >= 18 && h <= 22) lines.push('Летний вечер: над Кремлём носятся стрижи.');
  if (e.sun.alt < 0 && e.sun.alt > -12) lines.push('Кремль уже в подсветке: Кул-Шариф светится бирюзой.');
  const st = stalls(e);
  if (st.includes('icecream')) lines.push('На набережной работают ларьки: мороженое, кукуруза и горячие эчпочмаки.');
  else if (st.includes('tea')) lines.push('На набережной наливают горячий чай с чабрецом.');
  return lines;
}

