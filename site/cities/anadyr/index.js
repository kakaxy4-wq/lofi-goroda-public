function env(ms, local) {
  const mo = local.getUTCMonth() + 1, day = local.getUTCDate();
  return {
    winter: mo >= 11 || mo <= 4 || (mo === 10 && day >= 15) || (mo === 5 && day < 25), // снег с середины октября до конца мая
    autumn: (mo === 9) || (mo === 10 && day < 15),
  };
}

function ticker(e) {
  const lines = [], mo = e.local.getUTCMonth() + 1, h = e.local.getUTCHours();
  lines.push('Анадырь — самый восточный город России.');
  if (mo === 12 || mo === 1) lines.push('Зимой день в Анадыре короткий: солнце встаёт ненадолго и низко ходит над сопками.');
  if (mo === 6 || mo === 7) lines.push('Белые ночи: в июне в Анадыре почти не темнеет.');
  if (e.winter && e.weather.wind >= 10) lines.push('Пурга: ветер гонит снег вдоль дороги, тепляк парит у колодца.');
  else if (e.winter) lines.push('Снег здесь лежит с октября до конца мая. На тепляке его нет — плиты греют трубы.');
  if (mo >= 5 && mo <= 10) lines.push('У помоек дежурят бакланы — так здесь зовут больших чаек.');
  else lines.push('Зимой чайки улетают, и у помоек хозяйничают вороны.');
  if (h >= 9 && h < 22) lines.push('ТЦ «Новомариинский» открыт: название — от Ново-Мариинска, так Анадырь звали при основании в 1889 году.');
  return lines;
}

