function env(ms, local) {
  const mo = local.getUTCMonth() + 1, day = local.getUTCDate();
  return {
    winter: mo === 12 || mo <= 3 || (mo === 11 && day >= 15),
    frozen: mo === 12 || mo === 1 || mo === 2 || mo === 3 || (mo === 11 && day >= 28) || (mo === 4 && day <= 12), // ледостав в конце ноября, ледоход в середине апреля
    autumn: (mo === 9 && day >= 5) || mo === 10 || (mo === 11 && day < 15),
    navigation: (mo === 5 && day >= 20) || (mo >= 6 && mo <= 8) || (mo === 9 && day <= 20),
  };
}

function ticker(e) {
  const lines = [], h = e.local.getUTCHours(), mo = e.local.getUTCMonth() + 1;
  if (e.frozen) lines.push('Река Вологда подо льдом — по нему протоптаны тропинки, у лунок сидят рыбаки.');
  else if (e.navigation && h >= 10 && h <= 21) lines.push('Навигация: по реке Вологде ходят прогулочные теплоходы.');
  if (mo === 6) lines.push('Июнь: ночи в Вологде светлые, небо на севере не темнеет до утра.');
  if (e.autumn) lines.push('Осень: деревья Кремлёвского сада желтеют над рекой.');
  if (e.local.getUTCMinutes() < 10) lines.push('Куранты на колокольне Софийского собора отбивают часы с 1871 года.');
  const st = stalls(e);
  if (st.includes('plombir')) lines.push('На набережной продают пломбир на вологодских сливках, рядом — ларёк с кружевом.');
  else if (st.includes('teastall')) lines.push('На набережной наливают горячий чай с пряниками.');
  return lines;
}

