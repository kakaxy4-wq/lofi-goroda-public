function env(ms, local) {
  const mo = local.getUTCMonth() + 1, day = local.getUTCDate();
  return {
    winter: mo === 12 || mo <= 3 || (mo === 11 && day >= 22),
    frozen: mo === 12 || mo <= 3 || (mo === 4 && day <= 12), // Клязьма встаёт в конце ноября — начале декабря, вскрывается в середине апреля
    autumn: (mo === 9 && day >= 10) || mo === 10 || (mo === 11 && day < 22),
    navigation: (mo >= 5 && mo <= 9), // сезон байдарок и лодок
  };
}

function ticker(e) {
  const lines = [], h = e.local.getUTCHours(), mo = e.local.getUTCMonth() + 1;
  if (e.frozen) lines.push('Клязьма подо льдом — в пойме лыжня и рыбаки у лунок.');
  else if (e.navigation && h >= 9 && h <= 20) lines.push('По Клязьме сплавляются байдарочники.');
  if (mo >= 5 && mo <= 8 && h >= 18 && h <= 22) lines.push('Летний вечер: над соборным холмом носятся стрижи.');
  if (e.sun.alt < 0 && e.sun.alt > -12) lines.push('Соборы уже в подсветке: золотые шлемы Успенского видно из-за реки.');
  if (h >= 6 && h < 23) lines.push('Под холмом вдоль реки идут поезда: Москва — Владимир — Нижний Новгород.');
  const ks = stalls(e).map((s) => s.k);
  const NAMES = { icecream: 'мороженое', cherry: 'владимирская вишня', cucumber: 'малосольные огурцы', kalach: 'муромские калачи' };
  if (ks.includes('cherry')) lines.push('Июль — время владимирской вишни.');
  if (ks.includes('icecream')) lines.push(`На набережной работают ларьки: ${ks.map((k) => NAMES[k]).filter(Boolean).join(', ')}.`);
  else if (ks.includes('tea')) lines.push('На набережной наливают горячий чай к муромскому калачу.');
  return lines;
}

