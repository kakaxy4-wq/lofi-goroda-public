function env(ms, local) {
  const mo = local.getUTCMonth() + 1, day = local.getUTCDate();
  return {
    winter: mo === 12 || mo <= 2 || (mo === 11 && day >= 20) || (mo === 3 && day <= 15), // мягкая: снег только на хребте
    frozen: false, // Чёрное море у Сочи не замерзает
    autumn: (mo === 10 && day >= 20) || (mo === 11 && day < 20),
    navigation: mo >= 3, // прогулочные катера — с марта по декабрь, порт работает круглый год
  };
}

function ticker(e) {
  const lines = [], h = e.local.getUTCHours(), mo = e.local.getUTCMonth() + 1;
  if (e.winter) lines.push('Зима в Сочи: у моря плюс, а на вершинах Кавказа лежит снег.');
  if (e.navigation && h >= 9 && h < 20) lines.push('Из порта уходят прогулочные катера — морские прогулки вдоль берега.');
  if (mo >= 6 && mo <= 9 && h >= 9 && h < 20) lines.push('Купальный сезон: на городских пляжах людно до самого заката.');
  if (mo >= 5 && mo <= 8 && h >= 18 && h <= 21) lines.push('Летний вечер: над набережной носятся стрижи.');
  if (e.sun.alt < 0 && e.sun.alt > -12) lines.push('Морской вокзал уже в подсветке — звезду на шпиле видно издалека.');
  if (e.sun.alt < -6) lines.push('На мысу мигает Сочинский маяк — он светит судам с конца XIX века.');
  const st = stalls(e);
  if (st.includes('corn')) lines.push('На набережной продают варёную кукурузу, чурчхелу и мороженое.');
  if (st.includes('mandarin')) lines.push('Сезон мандаринов: на набережной продают мандарины из Абхазии.');
  else if (st.includes('tea')) lines.push('На набережной наливают горячий краснодарский чай.');
  return lines;
}

