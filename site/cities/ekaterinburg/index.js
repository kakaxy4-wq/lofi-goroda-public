function env(ms, local) {
  const mo = local.getUTCMonth() + 1, day = local.getUTCDate();
  return {
    winter: (mo === 11 && day >= 10) || mo === 12 || mo <= 3 || (mo === 4 && day <= 5),
    frozen: (mo === 11 && day >= 20) || mo === 12 || mo <= 3 || (mo === 4 && day <= 15), // пруд встаёт в ноябре, вскрывается в апреле (ориентировочно)
    autumn: mo === 9 || mo === 10 || (mo === 11 && day < 10),
    navigation: (mo === 5 && day >= 20) || (mo >= 6 && mo <= 8) || (mo === 9 && day <= 15),
  };
}

function ticker(e) {
  const lines = [], h = e.local.getUTCHours(), mo = e.local.getUTCMonth() + 1, d = e.local.getUTCDate();
  if (e.frozen) lines.push('Городской пруд подо льдом. Плотинка в снегу, проспект Ленина идёт прямо по плотине.');
  else if (e.navigation && h >= 11 && h < 21) lines.push('Навигация: по Городскому пруду ходят прогулочные катера, на воде лодки и катамараны.');
  if ((mo === 12 && d >= 29) || (mo === 1 && d <= 18)) lines.push('Новогодние каникулы: на Плотинке ёлка и ледовые горки.');
  if (e.sun.alt < -2) lines.push('Вечер: башня «Исеть» и «Высоцкий» в огнях, на Плотинке зажглись фонари.');
  if (e.autumn) lines.push('Уральская осень: берёзы вдоль пруда желтеют уже в сентябре.');
  if (mo === 10 && d === 5) lines.push('5 октября — день рождения памятника клавиатуре на набережной Исети (открыт в 2005 году).');
  if (h >= 7 && h < 22) lines.push('По проспекту Ленина ходят трамваи.');
  const st = stalls(e);
  if (st.includes('icecream')) lines.push('На набережной: мороженое, горячие шаньги и уральские самоцветы.');
  else if (st.includes('tea')) lines.push('На набережной наливают горячий чай, к нему — шаньги с картошкой.');
  return lines;
}

