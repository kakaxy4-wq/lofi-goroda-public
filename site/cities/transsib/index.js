function ticker(e) {
  const tr = e.train, lines = []; // «где мы» — в подзаголовке и на схеме маршрута, не в строке
  for (const [a, b, line] of ALONG) if (tr.km >= a && tr.km <= b) lines.push(line);
  if (tr.speed > 0) lines.push('Весь Транссиб электрифицирован: за окном опоры контактной сети.');
  if (e.autumn) lines.push('Осень: берёзы вдоль пути золотые, лиственницы роняют хвою.');
  if (e.winter) lines.push('Зимой лиственница голая, берёзы белые: лес прозрачный, в инее.');
  lines.push('Чай в купе — в стакане с подстаканником.');
  return lines;
}

