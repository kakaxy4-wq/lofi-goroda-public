function env(ms, local) {
  const mo = local.getUTCMonth() + 1, day = local.getUTCDate();
  return {
    winter: mo === 12 || mo === 1 || mo === 2 || (mo === 3 && day <= 10),
    // Преголя в центре обычно не замерзает: лёд бывает лишь после недели морозов ниже −10°, поэтому по календарю — никогда
    frozen: false,
    autumn: (mo === 9 && day >= 15) || mo === 10 || (mo === 11 && day < 25),
    navigation: (mo === 4 && day >= 20) || (mo >= 5 && mo <= 10),
  };
}

function ticker(e) {
  const lines = [], h = e.local.getUTCHours(), mo = e.local.getUTCMonth() + 1;
  if (e.weather.kind === 'fog') lines.push('Туман над Преголей: шпиль собора то проступает, то исчезает.');
  if (e.winter) lines.push('Балтийская зима мягкая: Преголя в центре почти никогда не замерзает.');
  if (korablikRun(e) >= 0) lines.push('От причала у Рыбной деревни отошёл прогулочный кораблик.');
  if (isNavyDay(e.local)) lines.push('День ВМФ: корабли у Музея Мирового океана в флагах расцвечивания.');
  if (mo >= 5 && mo <= 8 && h >= 18 && h <= 22) lines.push('Летний вечер: над Преголей носятся стрижи.');
  if (e.sun.alt < 0 && e.sun.alt > -12) lines.push('Собор на острове Канта уже в подсветке.');
  if (h >= 18 && h < 21) lines.push('Вечер — время органных концертов в Кафедральном соборе.');
  const st = stalls(e);
  if (st.includes('icecream')) lines.push('На набережной мороженое, кофе, копчёная рыба и янтарь.');
  else if (st.includes('tea')) lines.push('На набережной наливают горячий чай и какао, рядом — марципан.');
  return lines;
}

