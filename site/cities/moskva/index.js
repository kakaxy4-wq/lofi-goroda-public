function env(ms, local) {
  const mo = local.getUTCMonth() + 1, day = local.getUTCDate();
  return {
    winter: mo === 12 || mo <= 2 || (mo === 3 && day < 20) || (mo === 11 && day >= 25),
    frozen: false, // в центре Москва-река почти не замерзает, трамвайчики ходят круглый год
    autumn: (mo === 9 && day >= 15) || mo === 10 || (mo === 11 && day < 25),
  };
}

function ticker(e) {
  const lines = [], h = e.local.getUTCHours(), mo = e.local.getUTCMonth() + 1;
  lines.push('Куранты Спасской башни отбивают каждую четверть часа.');
  if (h >= 10 && h <= 23) lines.push(e.winter ? 'Даже зимой по реке идут трамвайчики — сквозь ледяную крошку.' : 'По Москве-реке идут прогулочные трамвайчики.');
  if (e.sun.alt < 0 && e.sun.alt > -14) lines.push('Кремль уже в подсветке, на башнях горят рубиновые звёзды.');
  if (mo >= 6 && mo <= 8 && h >= 19 && h <= 22) lines.push('Летний вечер: на набережной гуляют до темноты.');
  const st = stalls(e);
  if (st.includes('sbiten')) lines.push('На Софийской набережной наливают горячий сбитень и пекут блины.');
  else if (st.includes('icecream')) lines.push('На набережной продают пломбир в вафельном стаканчике и блины.');
  else if (st.includes('coffee')) lines.push('На набережной открыты ларьки: кофе с собой и блины.');
  return lines;
}

