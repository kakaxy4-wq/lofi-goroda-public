function env(ms, local) {
  const mo = local.getUTCMonth() + 1, day = local.getUTCDate();
  return {
    winter: (mo === 12 && day >= 20) || mo === 1 || (mo === 2 && day <= 10), // мягкая: снег редко и ненадолго
    // Затон схватывается льдом только в редкие морозные зимы: условно одна зима из шести, конец января
    frozen: local.getUTCFullYear() % 6 === 3 && mo === 1 && day >= 20,
    autumn: (mo === 10 && day >= 10) || mo === 11 || (mo === 12 && day < 15),
    navigation: (mo === 4 && day >= 15) || (mo >= 5 && mo <= 10) || (mo === 11 && day <= 15),
  };
}

function ticker(e) {
  const lines = [], h = e.local.getUTCHours(), mo = e.local.getUTCMonth() + 1;
  if (e.frozen) lines.push('Редкий случай: Затон схватился тонким льдом.');
  else if (e.navigation && h >= 10 && h <= 21) lines.push('Навигация: от Кубанской набережной ходят прогулочные теплоходы.');
  if (mo >= 6 && mo <= 8 && h >= 18 && h <= 22) lines.push('Жаркий вечер: над Затоном носятся стрижи.');
  if (e.sun.alt < 0 && e.sun.alt > -12) lines.push('Сумерки: Поцелуев мост зажигает разноцветную подсветку.');
  const st = stalls(e);
  if (st.includes('cherry')) lines.push('Сезон черешни: на набережной продают кубанскую черешню.');
  else if (st.includes('corn')) lines.push('На набережной — варёная кукуруза, квас из бочки и мороженое.');
  else if (st.includes('hurma')) lines.push('Осень на юге: на лотках хурма.');
  else if (st.includes('mandarin')) lines.push('Зима мягкая: мандарины и горячий чай на набережной.');
  return lines;
}

