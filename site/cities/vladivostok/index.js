function env(ms, local) {
  const mo = local.getUTCMonth() + 1, day = local.getUTCDate();
  return {
    winter: mo === 12 || mo <= 2 || (mo === 3 && day <= 15) || (mo === 11 && day >= 25),
    frozen: false, // бухта рабочая и целиком не замерзает: частичный лёд рисуем сами (ice)
    ice: (mo === 12 && day >= 25) || mo === 1 || (mo === 2 && day <= 20),
    autumn: mo === 10 || (mo === 11 && day < 25),
    navigation: true, // порт и паромы работают круглый год
  };
}

function ticker(e) {
  const lines = [], h = e.local.getUTCHours(), m = e.local.getUTCMinutes(), mo = e.local.getUTCMonth() + 1;
  if (isCityDaySalute(e.local) && h >= 18 && h < 23) lines.push('Дни рождения города: вечером в 22:00 — салют.');
  if ((h === 11 && m >= 45) || (h === 12 && m < 5)) lines.push('В полдень на Корабельной набережной стреляет пушка — сверяйте часы.');
  if (e.ice) lines.push('Морозы: у берегов Золотого Рога лёд, по фарватеру ходят буксиры.');
  if (mo >= 4 && mo <= 7 && h < 11) lines.push('Сезон морских туманов: с утра мост может спрятаться в белой пелене.');
  if (e.sun.alt < -2) lines.push('Золотой мост в подсветке — ванты светятся, как струны.');
  if (h >= 7 && h < 20) lines.push('По Золотому мосту идёт поток машин на Чуркин и обратно.');
  if (e.autumn) lines.push('Осень в Приморье — лучшее время года: тепло, сухо, сопки рыжеют.');
  const st = stalls(e);
  if (st.includes('scallop')) lines.push('На набережной жарят гребешок и продают пян-се с пылу с жару.');
  else if (st.includes('pyanse')) lines.push('На набережной продают пян-се — горячие пирожки на пару.');
  if (st.includes('tea')) lines.push('Холодно: в ларьке наливают горячий чай.');
  return lines;
}

