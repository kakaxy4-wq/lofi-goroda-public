function env(ms, local) {
  const mo = local.getUTCMonth() + 1, day = local.getUTCDate();
  return {
    winter: mo === 12 || mo <= 3 || (mo === 11 && day >= 15),
    frozen: mo === 12 || mo <= 3 || (mo === 11 && day >= 25) || (mo === 4 && day <= 15), // пруд подо льдом
    autumn: (mo === 9 && day >= 5) || mo === 10 || (mo === 11 && day < 15),
    navigation: (mo >= 5 && mo <= 9),
  };
}

function ticker(e) {
  const lines = [], h = e.local.getUTCHours();
  if (e.frozen) lines.push('Пруд подо льдом — на нём рыбаки и лыжники.');
  else if (e.navigation && h >= 10 && h <= 21) lines.push('Навигация: по пруду ходят прогулочные теплоходы.');
  if (e.sun.alt < 0 && e.sun.alt > -14) lines.push('Монумент «Навеки с Россией» в подсветке, колесо обозрения переливается огнями.');
  const st = stalls(e);
  if (st.includes('pelmeni')) lines.push('На набережной горячие пельмени и перепечи.');
  else if (st.includes('kvas')) lines.push('На набережной квас, мороженое и перепечи — удмуртские открытые пирожки.');
  return lines;
}

