function env(ms, local) {
  const mo = local.getUTCMonth() + 1, day = local.getUTCDate();
  return {
    winter: mo === 12 || mo <= 2 || (mo === 3 && day <= 20) || (mo === 11 && day >= 20),
    frozen: (mo === 12 && day >= 15) || mo === 1 || mo === 2 || mo === 3 || (mo === 4 && day <= 5), // ледостав в декабре, ледоход в начале апреля (примерно)
    autumn: (mo === 9 && day >= 15) || mo === 10 || (mo === 11 && day < 20),
    navigation: (mo === 4 && day >= 15) || (mo >= 5 && mo <= 9) || (mo === 10 && day <= 20),
  };
}

function ticker(e) {
  const lines = [], h = e.local.getUTCHours(), mo = e.local.getUTCMonth() + 1;
  if (e.frozen) lines.push('Волга подо льдом. В Рождествено ходят суда на воздушной подушке — только пока светло.');
  else if (e.navigation && h >= 7 && h <= 21) lines.push('Навигация: с речного вокзала уходят теплоходы в Рождествено и «Валдаи» в Ширяево.');
  if (e.sun.alt < 0 && e.sun.alt > -12) lines.push('Монумент Славы и «Ладья» в вечерней подсветке.');
  if (e.autumn) lines.push('Осень: Жигули за Волгой рыжеют, на набережной шуршат листья.');
  if (mo >= 6 && mo <= 7 && h >= 19 && h <= 22) lines.push('Летом солнце садится за Жигули — смотрите на северо-запад.');
  if (mo >= 6 && mo <= 8 && h >= 10 && h <= 19 && !e.frozen) lines.push('Лето: на пляже у набережной загорают и купаются.');
  const st = stalls(e);
  if (st.includes('icecream')) lines.push('На набережной: мороженое, кукуруза и магниты с «Ладьёй».');
  else if (st.includes('tea')) lines.push('На набережной наливают горячий чай, к нему — блины.');
  return lines;
}

