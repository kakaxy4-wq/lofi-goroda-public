function env(ms, local) {
  const mo = local.getUTCMonth() + 1, day = local.getUTCDate();
  return {
    winter: mo >= 11 || mo <= 4 || (mo === 10 && day >= 20) || (mo === 5 && day <= 15), // снег на сопках полгода
    frozen: false, // Кольский залив не замерзает: Нордкапское течение, ветвь Гольфстрима
    autumn: mo === 9 || (mo === 10 && day < 20),
    navigation: true, // незамерзающий порт работает круглый год
  };
}

const polarNight = (mo, d) => (mo === 12 && d >= 2) || (mo === 1 && d <= 11);
const polarDay = (mo, d) => (mo === 5 && d >= 22) || mo === 6 || (mo === 7 && d <= 22);

function ticker(e) {
  const lines = [], h = e.local.getUTCHours(), mo = e.local.getUTCMonth() + 1, d = e.local.getUTCDate();
  if (polarNight(mo, d)) lines.push('Полярная ночь: солнце не поднимается над горизонтом до 11 января, днём — пара часов синих сумерек.');
  if (mo === 1 && d > 11 && d <= 31) lines.push('Солнце вернулось после полярной ночи — каждый день оно выше над сопками.');
  if (polarDay(mo, d)) lines.push('Полярный день: солнце не заходит до 22 июля, в полночь оно низко над сопками на севере.');
  lines.push('Кольский залив не замерзает даже в морозы — порт работает круглый год.');
  if ((mo >= 9 || mo <= 4) && e.sun.alt < -12) lines.push('Тёмная ночь: если небо ясное, стоит поглядывать вверх — вдруг сияние.');
  if (mo === 3) lines.push('Март — время Праздника Севера: лыжные гонки и гонки на оленьих упряжках, традиция с 1934 года.');
  if (e.sun.alt < 0 && h >= 16) lines.push('Ледокол «Ленин» у Морского вокзала в огнях — он здесь музей с 2009 года.');
  const st = stalls(e);
  if (st.includes('moroshka')) lines.push('Конец лета — на набережной продают морошку из тундры.');
  if (st.includes('icecream')) lines.push('Короткое северное лето: на набережной мороженое.');
  if (st.includes('teastall')) lines.push('На набережной наливают горячий чай и продают выпечку.');
  return lines;
}

