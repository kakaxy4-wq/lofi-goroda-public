function env(ms, local) {
  const mo = local.getUTCMonth() + 1, day = local.getUTCDate();
  return {
    winter: mo === 12 || mo <= 3 || (mo === 11 && day >= 20),
    frozen: (mo === 12 && day >= 5) || mo === 1 || mo === 2 || mo === 3 || (mo === 4 && day <= 10), // Волга подо льдом
    autumn: (mo === 9 && day >= 10) || mo === 10 || (mo === 11 && day < 20),
    navigation: (mo >= 5 && mo <= 9) || (mo === 10 && day <= 15),
  };
}

function ticker(e) {
  const lines = [], h = e.local.getUTCHours(), mo = e.local.getUTCMonth() + 1;
  if (isCityDay(e.local)) lines.push('Сегодня День города! В 23:00 — салют над Стрелкой.');
  if (e.frozen) lines.push('Волга подо льдом — тихо, только ветер гоняет позёмку.');
  else if (e.navigation && h >= 8 && h <= 21) lines.push('Навигация: по Волге идут теплоходы, от Тверицкой пристани ходит катер к Речному вокзалу.');
  if (katerRun(e) >= 0) lines.push('Тверицкий катер сейчас на переправе.');
  if (meteorRun(e)) lines.push('По Волге проносится «Метеор».');
  if (fountainsOn(e) && h >= 19) lines.push('На Стрелке работают фонтаны, вечером — с подсветкой.');
  if (mo >= 6 && mo <= 8 && h >= 18 && h <= 22) lines.push('Летний вечер: над Волгой носятся стрижи.');
  if (e.sun.alt < 0 && e.sun.alt > -12) lines.push('Успенский собор уже в подсветке: золотые купола видно с того берега.');
  const st = stalls(e);
  if (st.includes('icecream')) lines.push('На набережной работают ларьки: мороженое, квас из бочки и кукуруза.');
  else if (st.includes('tea')) lines.push('На набережной наливают горячий чай, рядом — пошехонский сыр.');
  return lines;
}

